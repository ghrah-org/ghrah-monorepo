"""从 Python 作者模型单向生成 Ability 消费者的 Zod 校验器。"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from ghrah.ability.content import ContentDescription, ContentReadRequest, ContentReadResult
from ghrah.protocol.ability_tree import (
    AbilityTreeView,
    BindToolRequest,
    GrantAbilityRequest,
    RevokeAbilityRequest,
    TreeChangeResult,
    UnbindToolRequest,
)

MODELS = (
    AbilityTreeView,
    GrantAbilityRequest,
    RevokeAbilityRequest,
    BindToolRequest,
    UnbindToolRequest,
    TreeChangeResult,
    ContentReadRequest,
    ContentDescription,
    ContentReadResult,
)


def generated() -> str:
    """仅支持当前作者模型所需的 schema 子集，未知规则拒绝生成。"""
    definitions: dict[str, Any] = {}
    for model in MODELS:
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    lines = [
        "/** Generated by scripts/export_ability_contracts.py; edit the Python author. */",
        'import { z } from "zod";',
        "export const AbilityTreeIdSchema = z.string().regex(/^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/);",
    ]
    emitted: set[str] = set()

    def expression(schema: dict[str, Any]) -> str:
        if "$ref" in schema:
            name = schema["$ref"].rsplit("/", 1)[-1]
            emit(name)
            return name + "Schema"
        if "const" in schema:
            return f"z.literal({json.dumps(schema['const'], ensure_ascii=False)})"
        if "enum" in schema:
            return f"z.enum({json.dumps(schema['enum'], ensure_ascii=False)})"
        if "anyOf" in schema:
            return "z.union([" + ",".join(expression(item) for item in schema["anyOf"]) + "])"
        kind = schema.get("type")
        if kind == "object":
            if "properties" not in schema:
                return "z.record(z.unknown())"
            fields = []
            for key, item in schema["properties"].items():
                value = expression(item)
                if key not in schema.get("required", []):
                    default = item.get("default", [] if item.get("type") == "array" else None)
                    value += f".default({json.dumps(default, ensure_ascii=False)})"
                fields.append(f"{json.dumps(key)}:{value}")
            return "z.object({" + ",".join(fields) + "}).strict()"
        if kind == "array":
            value = "z.array(" + expression(schema["items"]) + ")"
            for rule, method in (("minItems", "min"), ("maxItems", "max")):
                if rule in schema:
                    value += f".{method}({schema[rule]})"
            return value
        if kind == "null":
            return "z.null()"
        if kind == "boolean":
            return "z.boolean()"
        if kind == "string":
            value = "z.string()"
            if schema.get("format") == "date-time":
                value += ".datetime()"
            if "pattern" in schema:
                value += ".regex(new RegExp(" + json.dumps(schema["pattern"]) + "))"
            return value
        if kind in {"integer", "number"}:
            value = "z.number()" + (".int()" if kind == "integer" else "")
            for rule, method in (("minimum", "min"), ("maximum", "max")):
                if rule in schema:
                    value += f".{method}({schema[rule]})"
            return value
        raise ValueError(f"未支持的 schema: {schema}")

    def emit(name: str) -> None:
        if name in emitted:
            return
        value = expression(definitions[name])
        if name == "AbilityNode":
            value += ".refine(v=>new Set(v.operations.map(x=>x.key)).size===v.operations.length)"
        if name == "AbilityTreeView":
            for field, key in (("abilities", "alias"), ("bound_tools", "name")):
                value += f".refine(v=>new Set(v.{field}.map(x=>x.{key})).size===v.{field}.length)"
        if name == "TreeChangeResult":
            value += ".refine(v=>(v.view===null)!==(v.error===null))"
        lines.append(f"export const {name}Schema = {value};")
        lines.append(f"export type {name} = z.infer<typeof {name}Schema>;")
        emitted.add(name)

    for model in MODELS:
        emit(model.__name__)
    return "\n".join(lines) + "\n"


def main() -> None:
    """生成或者核对字段和约束的单向产物。"""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / (
        "ghrah-observer-webui/packages/protocol/src/ability-tree.generated.ts"
    )
    if args.check:
        if target.read_text() != generated():
            raise SystemExit("Ability contracts are stale")
    else:
        target.write_text(generated())


if __name__ == "__main__":
    main()
