import fs from "node:fs";
import { describe, expect, it } from "vitest";
import { z } from "zod";
import {
  ActionDescriptorSchema,
  CatalogSnapshotSchema,
  ContractDescriptorSchema,
  DiscoveredActionSchema,
  DiscoveredResourceSchema,
} from "./scheme.js";

const sample = JSON.parse(
  fs.readFileSync(new URL("./__snapshots__/scheme-discovery.json", import.meta.url), "utf8"),
) as {
  descriptor: z.input<typeof ContractDescriptorSchema>;
  catalog: z.input<typeof CatalogSnapshotSchema>;
  schemas: Record<string, { properties: Record<string, unknown> }>;
};

describe("Scheme descriptors generated by Python", () => {
  it("preserves the complete contract and filtered catalog", () => {
    expect(ContractDescriptorSchema.parse(sample.descriptor)).toEqual(sample.descriptor);
    expect(CatalogSnapshotSchema.parse(sample.catalog)).toEqual(sample.catalog);
  });
  it("rejects duplicate actions and unknown fields", () => {
    expect(() =>
      ContractDescriptorSchema.parse({
        ...sample.descriptor,
        actions: [...sample.descriptor.actions, ...sample.descriptor.actions],
      }),
    ).toThrow();
    expect(() => CatalogSnapshotSchema.parse({ ...sample.catalog, hidden_count: 42 })).toThrow();
  });
  it("aligns every public field with Python JSON Schema", () => {
    const pairs = [
      [ActionDescriptorSchema, sample.schemas.ActionDescriptor],
      [ContractDescriptorSchema.innerType(), sample.schemas.ContractDescriptor],
      [DiscoveredActionSchema, sample.schemas.DiscoveredAction],
      [DiscoveredResourceSchema, sample.schemas.DiscoveredResource],
      [CatalogSnapshotSchema, sample.schemas.CatalogSnapshot],
    ] as const;
    for (const [schema, python] of pairs) {
      expect(Object.keys(schema.shape).sort()).toEqual(Object.keys(python.properties).sort());
      expect(schema instanceof z.ZodObject).toBe(true);
    }
  });
  it("represents summary-only visibility without granting invocation", () => {
    const action = DiscoveredActionSchema.parse({
      ...sample.catalog.entries[0].actions[0],
      invokable: false,
      input_schema: null,
      output_schema: null,
    });
    expect(action.invokable).toBe(false);
    expect(action.input_schema).toBeNull();
  });
});
